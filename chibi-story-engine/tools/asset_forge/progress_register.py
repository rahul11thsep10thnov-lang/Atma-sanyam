"""Write docs/generated/PROGRESS_REGISTER.md from the files on disk and the verification report. Numbers are counted, never typed in."""
from __future__ import annotations

import json
from pathlib import Path

from engine.asset_manager.library import AssetLibrary

from . import verify_ext
from ..catalogue.build_catalogue import build as build_catalogue

ROOT = Path(__file__).resolve().parents[2]


def main() -> None:
    lib = AssetLibrary(ROOT / "asset_library")
    rep = verify_ext.verify(lib, only_new=True)
    st = rep["stats"]
    cat = build_catalogue(lib)
    env, chars, comps = st["environments"], st["characters"], st["components"]
    lines = [
        "# Vector library expansion: progress register",
        "",
        "Generated by `python -m tools.asset_forge.progress_register`. Every number is counted from `asset_library/` and the independent verifier "
        "(`tools/asset_forge/verify_ext.py`); nothing is a planned target. Assets are registered with approval status **pending**.",
        "",
        f"Verifier result: **{'no problems' if rep['ok'] else str(len(rep['problems'])) + ' problems'}**.",
        "",
        "## Counts",
        "",
        f"- Components (SVG master + PNG each): **{comps['count']}**: " + ", ".join(f"{k} {v}" for k, v in sorted(comps["by_kind"].items())),
        f"- Master backgrounds: **{env['count']}** in {len(env['by_category'])} categories: " + ", ".join(f"{k} {v}" for k, v in sorted(env["by_category"].items())),
        f"- Background layers: **{env['layers']}** (each with an SVG master and a runtime PNG); adjustable-scare layers: {env['scare_layers']}",
        f"- New characters: **{chars['count']}**: " + ", ".join(f"{k} {v}" for k, v in sorted(chars["by_category"].items())) + " (the 9 original characters are untouched)",
        f"- Stories tracked in the master catalogue: **{cat['totals']['stories']}** (built as Story Definitions: {cat['totals']['implemented']}; all required assets matched: {cat['totals']['fully_covered']})",
        "",
        "## Phases",
        "",
        "| # | Phase | Status |",
        "|---|---|---|",
        "| 1 | Source and architecture audit | done (notes in `docs/VECTOR_LIBRARY.md`) |",
        "| 2 | Audit of existing assets | done; original characters are untouched; gaps listed below |",
        "| 3 | Master story and asset catalogue | done as a seed list; **not** a complete catalogue and unverified against sources (`stories/master_catalogue.json`) |",
        "| 4 | Vector design system | done (`tools/asset_forge/kit.py`, `docs/VECTOR_LIBRARY.md`) |",
        f"| 5 | Characters | {chars['count']} new characters (human, animal, bird, mythological) |",
        f"| 6 | Components | {comps['count']} |",
        f"| 7 | Master backgrounds | {env['count']} in 13 categories |",
        "| 8 | Views, expressions, poses | 15 expressions and 15 poses per new character; **front view only**: side, three-quarter and back views are not delivered |",
        "| 9 | Compositions, lighting, weather | lighting, weather, season and scare-level variations work on every background through the existing engine; **separate wide / medium / close-up compositions are not delivered** |",
        "| 10 | Registry and database sync | done through the existing AssetLibrary and `sync_library`; no new table |",
        "| 11 | Library UI | galleries with search, category and approval filters; previews by time of day, weather, season, scare level; dashboard counts |",
        "| 12 | Story-to-asset retrieval | asset report endpoint and panel, environment overrides, more location tags |",
        "| 13 | Pipeline compatibility | new characters use the existing `biped_chibi` rig and clips; see tests |",
        "| 14 | QA and documentation | see `docs/VECTOR_LIBRARY.md` and the test files named there |",
        "",
        "## Known gaps (not hidden)",
        "",
        "- Original nine characters were not given SVG masters, the 15 expressions or the 15 poses.",
        "- Side, three-quarter and back character views; wide / medium / close-up background compositions.",
        "- Characters are all `biped_chibi`; the `quadruped_reptile` rig was not extended (turtle, lizard and snake are upright chibi figures).",
        "- Story catalogue needs the library cannot meet yet: " + "; ".join(f"{k}: {', '.join(v) or 'none'}" for k, v in cat["unmatched_needs"].items()),
        "- No human review has happened: every new asset is `pending`.",
        "",
    ]
    out = ROOT / "docs" / "generated" / "PROGRESS_REGISTER.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(out)
    if not rep["ok"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()

"""Write docs/generated/PROGRESS_REGISTER.md from the files on disk and the verification report. Numbers are counted, never typed in."""
from __future__ import annotations

import json
from pathlib import Path

from engine.asset_manager.library import AssetLibrary

from . import verify_ext
from ..catalogue.build_catalogue import build as build_catalogue

ROOT = Path(__file__).resolve().parents[2]


def main() -> None:
    lib = AssetLibrary(ROOT / "asset_library")
    rep = verify_ext.verify(lib, only_new=True)
    st = rep["stats"]
    cat = build_catalogue(lib)
    env, chars, comps = st["environments"], st["characters"], st["components"]
    from engine.asset_manager import completion
    comp = completion.compute(lib, ROOT)
    ch, en, sr = comp["characters"], comp["environments"], comp["story_research"]
    lines = [
        "# Vector library: progress and completion register",
        "",
        "Generated by `python -m tools.asset_forge.progress_register`. Every number is counted from `asset_library/`, the independent verifier "
        "(`tools/asset_forge/verify_ext.py`), the acceptance counters (`engine/asset_manager/completion.py`) and the research files; nothing is a planned target. "
        "All new and upgraded assets are **pending** review.",
        "",
        f"Verifier result: **{'no problems' if rep['ok'] else str(len(rep['problems'])) + ' problems'}**.",
        "",
        "## Counts",
        "",
        f"- Components (SVG master + PNG each): **{comps['count']}**: " + ", ".join(f"{k} {v}" for k, v in sorted(comps["by_kind"].items())),
        f"- Master backgrounds (wide): **{en['wide']}**; medium compositions **{en['medium']}**; close-up compositions **{en['closeup']}**; "
        f"{en['wide_with_all_three_compositions']} backgrounds have all three, {en['wide_without_variants']} have the wide composition only",
        f"- Characters: **{ch['total']}** ({', '.join(f'{k} {v}' for k, v in sorted(chars['by_category'].items()))} new, plus the original nine); rigs: " + ", ".join(f"{k} {v}" for k, v in sorted(ch["by_rig_template"].items())),
        f"- Characters with SVG masters {ch['with_svg_masters']}, four views {ch['with_four_views']}, 15 expressions {ch['with_15_expressions']}, 15 poses {ch['with_15_poses']}, validated rigs {ch['with_validated_rigs']}",
        f"- Original nine: {ch['original_nine_upgraded_to_v2']} upgraded to version 2 (version 1 intact), {ch['original_nine_fully_upgraded']} fully upgraded (SVG, four views, 15 + 15, valid rig)",
        f"- Story research: {sr['sources_consulted']} sources consulted, {sr['source_records']} source records and {sr['seed_entries']} seed entries; verified {sr['verified']}, cross-verified {sr['cross_verified']}, "
        f"unverified {sr['unverified']}, research pending {sr['research_pending']}; {sr['regions_with_a_consulted_source']} of {sr['regions_total']} regions have any consulted source",
        "",
        "## The five legacy gaps",
        "",
        "| Gap | Status |",
        "|---|---|",
        f"| 1. Four views | **{'Closed' if ch['with_four_views'] == ch['total'] else 'Partly closed'}.** {ch['with_four_views']} of {ch['total']} characters have front, side, three-quarter and back views. "
        "Side and back (and head-on / tail-on for reptiles) are drawn separately per angle; the three-quarter view of the biped characters is the front art turned about the vertical axis, "
        "and for reptiles it is the side body foreshortened with the head-on head turned toward the viewer. Head-on views of reptiles fix the jaw and omit parts that cannot be seen. |",
        f"| 2. Three compositions | **{'Closed for the master backgrounds' if en['wide_with_all_three_compositions'] >= 171 else 'Partly closed'}.** {en['wide_with_all_three_compositions']} backgrounds have wide, medium and close-up compositions "
        f"(re-arranged, larger, fewer elements, scaled and pulled-together anchors; sky, wall and ground are shared). The {en['wide_without_variants']} original hand-coded backgrounds have SVG masters (version 2, PNGs unchanged) but no medium or close-up composition. |",
        f"| 3. Original nine upgraded | **{'Closed' if ch['original_nine_fully_upgraded'] == ch['original_total'] else 'Partly closed'}** ({ch['original_nine_fully_upgraded']} of {ch['original_total']} fully upgraded): SVG masters, four views, 15 expressions, 15 poses, valid rig; version 1 intact and retrievable; nothing is approved. |",
        "| 4. Reptile rigs | **Closed.** Articulated `quadruped_reptile` (crocodile, crocodile's wife, lizard), `chelonian` (turtle, tortoise) and `serpentine_reptile` (snake) with 20 new clips; "
        f"rig tests: {comp['rigs']['rig_test_results'].get('passed', 'not run')} passed. The old upright turtle, tortoise, snake and lizard remain in version 1. |",
        f"| 5. Story catalogue | **Partly closed.** {sr['sources_consulted']} real sources were fetched and parsed (Ryder's Panchatantra, Arnold's Hitopadesa, a 547-row Jataka table, the Perry Index via Wikipedia, Burton's Vikram and the Vampire, four regional collections). "
        "Burton's 1870 Vikram-Betal selection (11 tales) is indexed; Singhasan Battisi has no tale list yet, Akbar-Birbal and Tenali Raman have no edition index, most regions are unresearched. The collection register says so. |",
        "",
        "## Known gaps (not hidden)",
        "",
        "- A quadruped *mammal* rig was not built (mammals use the biped chibi rig); the biped three-quarter views are a turn of the front art, not redrawn.",
        "- Medium and close-up compositions for the 7 original hand-coded backgrounds (their drawing code is not parameterised for recomposition).",
        "- Story catalogue: see `docs/generated/STORY_RESEARCH_REGISTER.md`.",
        "- No human review has happened: every new or upgraded asset is `pending`.",
        "",
    ]
    out = ROOT / "docs" / "generated" / "PROGRESS_REGISTER.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(out)
    if not rep["ok"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()

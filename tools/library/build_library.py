"""Build the bundled picture library from the supplied landscape zips.

    python -I build_library.py <dir with z27/, z80/, zNew/> <repo root>

Reads every JPEG (1080 x 1920) from the three folders in that order, gives
each a stable id (ls_001 ...), and writes
  assets/library/ls_NNN.webp        the picture (1080 x 1920, WebP)
  assets/library/ls_NNN_t.webp      a 360 x 360 thumbnail
  src/content/bundledLibrary.generated.ts   the manifest the app reads

The kind of each picture (mountain, lake, ...) is set by hand in KINDS, in
the order the files are read; the app builds titles from it ("Lake 03").
"""
import glob, os, sys, json
from PIL import Image

src, root = sys.argv[1], sys.argv[2]
OUT = os.path.join(root, "assets", "library")
os.makedirs(OUT, exist_ok=True)

# m mountain · l lake · r river · w waterfall · v valley · c coast · f forest
# x flowers · p vintage print · b bird · t butterfly · a animal
KINDS = (
    "llllllllll" "lmllll" "fwwrww" "ccc" "aa"          # z27 001-027
    "mmmmmm" "vvm"                                    # z80 001-009
    "m" "vvm" "v" "l" "ppp" "r" "p" "v" "mmm" "l" "vlmm" "r" "m" "r" "xx" "rr" "m" "vvvrrrm" "v"  # z80 010-045
    "m" "l" "v" "mm"                                  # z80 046-050
    "m" "p" "t" "bbbbb" "l" "b" "b" "f" "p" "rr" "t" "r" "m" "vv" "l" "cccc" "wwww" "r"  # zNew 051-080
)
KIND = {
    "m": ("nature", "mountains", "mountain"), "l": ("nature", "lakes", "lake"), "r": ("nature", "rivers", "river"),
    "w": ("nature", "waterfalls", "waterfall"), "v": ("nature", "valleys", "valley"), "c": ("nature", "coast", "coast"),
    "f": ("nature", "forests", "forest"), "x": ("nature", "flowers", "flowers"), "p": ("nature", "vintage", "print"),
    "b": ("wildlife", "birds", "bird"), "t": ("wildlife", "butterflies", "butterfly"), "a": ("wildlife", "animals", "animal"),
}

# left out on purpose (by position in the order above): a cropped title overlay
# (ls_072), a personal email address watermarked across the picture (ls_086),
# and a readable vehicle number plate (ls_095). Their ids stay unused.
EXCLUDED = {71, 85, 94}

for old in glob.glob(os.path.join(OUT, "ls_*.webp")):
    os.remove(old)

files = []
for d in ("z27", "z80", "zNew"):
    files += sorted(glob.glob(os.path.join(src, d, "*.jpg")))
assert len(files) == len(KINDS), (len(files), len(KINDS))

items = []
counts = {}
for i, f in enumerate(files):
    if i in EXCLUDED:
        continue
    k = KINDS[i]
    cat, sub, kind = KIND[k]
    counts[kind] = counts.get(kind, 0) + 1
    ident = f"ls_{i + 1:03d}"
    im = Image.open(f).convert("RGB")
    assert im.size == (1080, 1920), (f, im.size)
    im.save(os.path.join(OUT, ident + ".webp"), "WEBP", quality=75, method=5)
    s = 360
    crop = im.crop((0, int(im.height * 0.18), im.width, int(im.height * 0.18) + im.width)).resize((s, s), Image.LANCZOS)
    crop.save(os.path.join(OUT, ident + "_t.webp"), "WEBP", quality=72, method=5)
    items.append({"id": ident, "cat": cat, "sub": sub, "kind": kind, "n": counts[kind]})

# the order the Home strip shows: round-robin over the subcategories, so the
# first twelve are a mix and not twelve lakes
order = []
for cat in ("nature", "wildlife"):
    groups = {}
    for it in items:
        if it["cat"] == cat:
            groups.setdefault(it["sub"], []).append(it)
    names = list(groups)
    while any(groups.values()):
        for nme in names:
            if groups[nme]:
                order.append(groups[nme].pop(0))
for rank, it in enumerate(order):
    it["pop"] = 800 - rank

lines = [
    "// GENERATED by tools/library/build_library.py - do not edit by hand.",
    "/* eslint-disable */",
    "export interface LibraryItem { id: string; cat: 'nature' | 'wildlife'; sub: string; kind: string; n: number; pop: number; thumb: number; full: number }",
    "export const LIBRARY_ITEMS: LibraryItem[] = [",
]
for it in items:
    lines.append(
        f"  {{ id: '{it['id']}', cat: '{it['cat']}', sub: '{it['sub']}', kind: '{it['kind']}', n: {it['n']}, pop: {it['pop']}, "
        f"thumb: require('../../assets/library/{it['id']}_t.webp'), full: require('../../assets/library/{it['id']}.webp') }},"
    )
lines.append("];")
open(os.path.join(root, "src", "content", "bundledLibrary.generated.ts"), "w").write("\n".join(lines) + "\n")
print(len(items), "pictures;", counts)
tot = sum(os.path.getsize(os.path.join(OUT, n)) for n in os.listdir(OUT) if n.startswith("ls_"))
print("bundled size MB:", round(tot / 1e6, 1))

"""Build the bundled Inspirational gallery from the supplied quote-card zip.

    python -I build_quotes.py <dir with the 100 quote_NNN.jpg> <repo root>

The cards came as 1080 x 1920 JPEGs with a caption bar from a concept sheet
baked into the bottom ("1 Watercolor Sunrise", "27", "001") and a thin strip
at the top. Each is cropped (top 2 %, bottom 14 %, and the sides to keep
9:16) and written as
  assets/library/qt_NNN.webp        the card (1080 x 1920, WebP)
  assets/library/qt_NNN_t.webp      a 360 x 360 thumbnail of the quote panel
  src/content/bundledQuotes.generated.ts
"""
import glob, os, sys
from PIL import Image

src, root = sys.argv[1], sys.argv[2]
OUT = os.path.join(root, "assets", "library")
os.makedirs(OUT, exist_ok=True)
for old in glob.glob(os.path.join(OUT, "qt_*.webp")):
    os.remove(old)

files = sorted(glob.glob(os.path.join(src, "quote_*.jpg")))
items = []
for i, f in enumerate(files):
    ident = f"qt_{i + 1:03d}"
    im = Image.open(f).convert("RGB")
    w, h = im.size
    top, bot = int(h * 0.02), int(h * 0.86)
    nh = bot - top
    nw = int(round(nh * 9 / 16))
    x0 = (w - nw) // 2
    card = im.crop((x0, top, x0 + nw, bot)).resize((1080, 1920), Image.LANCZOS)
    card.save(os.path.join(OUT, ident + ".webp"), "WEBP", quality=78, method=5)
    # the thumbnail: the middle of the quote panel, so the words show
    s = 760
    card.crop((160, 580, 160 + s, 580 + s)).resize((360, 360), Image.LANCZOS).save(os.path.join(OUT, ident + "_t.webp"), "WEBP", quality=72, method=5)
    items.append(ident)

lines = [
    "// GENERATED by tools/library/build_quotes.py - do not edit by hand.",
    "/* eslint-disable */",
    "export interface QuoteItem { id: string; n: number; thumb: number; full: number }",
    "export const QUOTE_ITEMS: QuoteItem[] = [",
]
for n, ident in enumerate(items, 1):
    lines.append(f"  {{ id: '{ident}', n: {n}, thumb: require('../../assets/library/{ident}_t.webp'), full: require('../../assets/library/{ident}.webp') }},")
lines.append("];")
open(os.path.join(root, "src", "content", "bundledQuotes.generated.ts"), "w").write("\n".join(lines) + "\n")
tot = sum(os.path.getsize(os.path.join(OUT, n)) for n in os.listdir(OUT) if n.startswith("qt_"))
print(len(items), "cards; bundled size MB:", round(tot / 1e6, 1))

// Bundles the app's real game reducers (src/games/defs/*.tsx and the pure
// rules they use) into backend/src/games/engines.generated.ts so the API can
// replay a finished game and compute its true result. One source of truth:
// the code the child plays is the code the server replays.
//
//   npm run engines:build   regenerate the file
//   npm run engines:check   fail if the committed file is out of date (CI)
//
// Only the pure game code is bundled. Everything else the games import (React,
// React Native, the UI kit, theme, audio) is replaced by an inert stub: the
// Views are never rendered on the server, only init / reduce / status run.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const outFile = path.join(repo, 'backend/src/games/engines.generated.ts');

/**
 * Games whose result is fully decided by discrete, validated choices, so a
 * replay proves it. Excluded on purpose: cricket (timing ticks), bowling and
 * football-penalty (analogue aim/power the client measures).
 */
export const REPLAYABLE = {
  chess: 'chess',
  'chess-tactics': 'chessTactics',
  'memory-cards': 'memoryCards',
  jigsaw: 'jigsaw',
  sudoku: 'sudoku',
  'word-search': 'wordSearch',
  'anagram-builder': 'anagramBuilder',
  'connect-four': 'connectFour',
  checkers: 'checkers',
  'science-quiz': 'scienceQuiz',
  'geography-quiz': 'geographyQuiz',
  'maze-runner': 'mazeRunner',
  ludo: 'ludo',
  'snakes-and-ladders': 'snakesAndLadders',
  'match-3': 'match3',
  'block-puzzle': 'blockPuzzle',
};

const gamesDir = path.join(repo, 'src/games') + path.sep;
const pure = (p) =>
  p === path.join(repo, 'src/games/engine.ts') ||
  p === path.join(repo, 'src/games/shared/quiz.tsx') ||
  p.startsWith(gamesDir + 'logic' + path.sep) ||
  p.startsWith(gamesDir + 'data' + path.sep) ||
  p.startsWith(gamesDir + 'defs' + path.sep);

const STUB = `
const make = () => {
  const target = function () {};
  const p = new Proxy(target, {
    get(_t, k) {
      if (k === Symbol.toPrimitive) return () => '';
      if (k === Symbol.iterator) return function* () {};
      if (k === '__esModule') return false;
      if (k === 'then') return undefined;
      return p;
    },
    // esbuild interop copies a module onto Object.create(getPrototypeOf(mod)); making the prototype the
    // stub itself lets a named import such as StyleSheet resolve to another stub.
    getPrototypeOf: () => p,
    apply: () => p,
    construct: () => p,
  });
  return p;
};
module.exports = make();
`;

const stubPlugin = {
  name: 'stub-non-pure',
  setup(b) {
    b.onResolve({ filter: /.*/ }, async (args) => {
      if (args.kind === 'entry-point' || args.pluginData?.inner) return null;
      if (args.path.startsWith('node:')) return { path: args.path, external: true };
      const local = args.path.startsWith('.') || path.isAbsolute(args.path);
      if (!local) return { path: args.path, namespace: 'stub' };
      const r = await b.resolve(args.path, { resolveDir: args.resolveDir, kind: args.kind, pluginData: { inner: true } });
      if (r.errors.length) return { errors: r.errors };
      return pure(r.path) ? { path: r.path } : { path: r.path, namespace: 'stub' };
    });
    b.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({ contents: STUB, loader: 'js' }));
  },
};

const entry = [
  ...Object.entries(REPLAYABLE).map(([, file], i) => `import d${i} from ${JSON.stringify(path.join(repo, 'src/games/defs', file + '.tsx'))};`),
  `export const ENGINES = { ${Object.keys(REPLAYABLE).map((id, i) => `${JSON.stringify(id)}: d${i}`).join(', ')} };`,
].join('\n');

const result = await build({
  stdin: { contents: entry, resolveDir: repo, sourcefile: 'engines-entry.ts', loader: 'ts' },
  bundle: true,
  write: false,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  minify: true,
  legalComments: 'none',
  jsx: 'automatic',
  define: { __DEV__: 'false', 'process.env.NODE_ENV': '"production"' },
  plugins: [stubPlugin],
  logLevel: 'error',
});
const code = result.outputFiles[0].text;
const hash = createHash('sha256').update(code).digest('hex').slice(0, 16);
const file = `// @ts-nocheck
// GENERATED by backend/scripts/bundleEngines.mjs from src/games. Do not edit.
// Regenerate with \`npm run engines:build\` (in backend/) after changing a replayable game.
export const ENGINE_IDS = ${JSON.stringify(Object.keys(REPLAYABLE))} as const;
export const ENGINE_BUNDLE_HASH = ${JSON.stringify(hash)};
/** CommonJS source; evaluating it yields \`{ ENGINES }\`, each a GameDefinition without a usable View. */
export const ENGINE_BUNDLE = ${JSON.stringify(code)};
`;
if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== file) {
    console.error('backend/src/games/engines.generated.ts is out of date. Run `npm run engines:build` in backend/ and commit the result.');
    process.exit(1);
  }
  console.log(`engines up to date (${hash}, ${Math.round(code.length / 1024)} KB)`);
} else {
  writeFileSync(outFile, file);
  console.log(`wrote ${path.relative(repo, outFile)} (${hash}, ${Math.round(code.length / 1024)} KB, ${Object.keys(REPLAYABLE).length} games)`);
}

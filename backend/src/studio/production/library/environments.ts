import { LocationCategory } from "@prisma/client";
import { ParticleSpec } from "../../engine25d/spec";

export type TimeBucket = "day" | "dusk" | "night";

export interface MidgroundElement {
  key: string;
  name: string;
  prompt: string;
  depth: number;
  /** Procedural motion the planner may enable (e.g. a train passing). */
  motion?: "pass_left" | "pass_right" | "idle";
  /** Width of the element in canvas widths (wide elements can travel across the frame). */
  widthFactor?: number;
}

export interface EnvironmentDescriptor {
  category: LocationCategory;
  label: string;
  /** Scene text that selects this environment. */
  keywords: RegExp;
  interior: boolean;
  /** Prompt for an empty background plate (people are always separate layers). */
  backgroundPrompt: string;
  midground: MidgroundElement[];
  foreground: { key: string; name: string; prompt: string }[];
  props: string[];
  ambience: string;
  particles: ParticleSpec["type"][];
  /** Where feet stand (canvas fraction) and where the horizon sits, for planning and shadows. */
  groundY: number;
  horizonY: number;
  /** Practical lights the location usually has, by time of day bucket. */
  practicalLights: { type: "streetlight" | "interior" | "window" | "neon" | "train" | "police" | "fire"; x: number; y: number; times: TimeBucket[]; flicker?: number }[];
  /** A visible steam source in the painted plate (e.g. a tea stall's kettle). */
  steamSource?: { x: number; y: number; depth: number };
  painter: string;
}


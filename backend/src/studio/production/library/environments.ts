export function getEnvironment(category: LocationCategory): EnvironmentDescriptor {
  return ENVIRONMENTS.find((e) => e.category === category) ?? ENVIRONMENTS.find((e) => e.category === "URBAN_STREET")!;
}

// Settings produced by the existing location extractor → categories.
const SETTING_TO_CATEGORY: Record<string, LocationCategory> = {
  "home interior": "HOME_INTERIOR",
  "police station": "POLICE_STATION",
  "courtroom exterior": "COURT",
  "hospital exterior": "DISTRICT_HOSPITAL",
  "village lane": "VILLAGE_ROAD",
  farmland: "FARM",
  "city street": "URBAN_STREET",
  "office exterior": "GOVERNMENT_BUILDING",
  "railway station": "RAILWAY_PLATFORM",
};

/**
 * Picks the environment for a shot. Only the scene's *place* fields (its
 * location label and background description) are used — narration such as
 * "police said…" must not turn every scene into a police station.
 */
export function detectEnvironment(placeText: string, settingLabel?: string): LocationCategory {
  for (const env of ENVIRONMENTS) {
    if (env.category !== "SUBSTITUTE" && env.keywords.test(placeText)) return env.category;
  }
  const setting = settingLabel?.split(",")[0].trim().toLowerCase();
  if (setting && SETTING_TO_CATEGORY[setting]) return SETTING_TO_CATEGORY[setting];
  return "URBAN_STREET";
}

export function timeBucket(timeOfDay: string): TimeBucket {
  if (timeOfDay === "night") return "night";
  if (timeOfDay === "evening") return "dusk";
  return "day";
}
